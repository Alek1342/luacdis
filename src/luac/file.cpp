#include "luac/file.hpp"
#include "lasm/output_stream.hpp"

void Luac::File::loadFromFile(char* path) {
    Luac::InputStream stream;
    stream.loadFromFile(path);
    load(&stream);
}

void Luac::File::load(Luac::InputStream* stream) {
    m_header.load(stream);
    m_prototype.load(stream);
    m_tail.load(stream);
}

void Luac::File::addLasmComment(Lasm::OutputStream* stream) {
    stream->reserve(1000);
    stream->write("; Lasm file generated by luacdis\n");
    stream->write("; all luac bytes can be controled except few in header\n");
    stream->write("; specifically luaс header signature \"\\x1BLua\"\n");
    stream->write("; luac header tail \"\\x19\\x93\\x0D\\x0A\\x1A\\x0A\"\n");
    stream->write("; number format allows only 0x00 0x04(same as 0x00) 0x01(numbers are ints)\n");
}

void Luac::File::printToFile(char* path) {
    Lasm::OutputStream stream;
    addLasmComment(&stream);
    m_header.print(&stream);
    m_prototype.print(&stream);
    m_tail.dump(path);
    stream.saveTo(path);
}